// Generates migrations/0002_seed.sql from server/seed.ts.
// Run with: pnpm db:seed:generate
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { seedData, type SeedDb } from '../server/seed';

const outFile = resolve(import.meta.dirname, '../migrations/0002_seed.sql');

const lines: string[] = [];
const rowCounters = new Map<string, number>();

const literal = (v: string | number | null) =>
  v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;

const sqlWriter: SeedDb = {
  prepare(sql) {
    const match = sql.match(/INSERT INTO (\w+)\s*\(([^)]*)\)/);
    if (!match) throw new Error(`Unsupported seed statement: ${sql}`);
    const [, table, columns] = match;

    return {
      run(...params) {
        lines.push(`INSERT INTO ${table} (${columns.replace(/\s+/g, ' ').trim()}) VALUES (${params.map(literal).join(', ')});`);
        // Fresh table + AUTOINCREMENT => ids are sequential from 1.
        const id = (rowCounters.get(table) ?? 0) + 1;
        rowCounters.set(table, id);
        return { lastInsertRowid: id };
      },
    };
  },
};

await seedData(sqlWriter);
writeFileSync(outFile, `-- Generated by scripts/generate-seed.ts from server/seed.ts. Do not edit by hand.\n${lines.join('\n')}\n`);
console.log(`Wrote ${lines.length} statements to ${outFile}`);
